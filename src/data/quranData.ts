export const NAMA_HARI = ['Minggu', 'Senin', 'Selasa', 'Rabu', 'Kamis', 'Jumat', 'Sabtu'];

export function getHariFromDate(dateStr: string): string {
  if (!dateStr) return '';
  const parts = dateStr.split('-');
  if (parts.length === 3) {
    const d = new Date(parseInt(parts[0]), parseInt(parts[1]) - 1, parseInt(parts[2]));
    return NAMA_HARI[d.getDay()] || '';
  }
  return '';
}

export function formatTanggalIndo(dateStr: string): string {
  if (!dateStr) return '';
  const months = [
    'Januari', 'Februari', 'Maret', 'April', 'Mei', 'Juni',
    'Juli', 'Agustus', 'September', 'Oktober', 'November', 'Desember'
  ];
  const parts = dateStr.split('-');
  if (parts.length === 3) {
    const day = parseInt(parts[2]);
    const monthIdx = parseInt(parts[1]) - 1;
    const year = parts[0];
    return `${day} ${months[monthIdx]} ${year}`;
  }
  return dateStr;
}

export function calculatePredikat(nilai: number) {
  if (nilai >= 90) return 'Mumtaz';
  if (nilai >= 80) return 'Jayyid Jiddan';
  if (nilai >= 70) return 'Jayyid';
  if (nilai >= 60) return 'Maqbul';
  return "I'adah";
}

