export function getHijriDateApprox(dateStr: string): string {
  if (!dateStr) return '9 Rabi\'ul Akhir 1448 H';
  // Reasonable approximate mapping for educational/certificate display
  const hijriMonths = [
    'Muharram', 'Safar', 'Rabi\'ul Awwal', 'Rabi\'ul Akhir',
    'Jumadil Awwal', 'Jumadil Akhir', 'Rajab', 'Sya\'ban',
    'Ramadhan', 'Syawwal', 'Dzulqa\'dah', 'Dzulhijjah'
  ];
  try {
    const parts = dateStr.split('-');
    if (parts.length === 3) {
      const year = parseInt(parts[0]);
      const month = parseInt(parts[1]);
      const day = parseInt(parts[2]);
      // Approximate 2026 is 1447-1448 H
      const hYear = year - 578;
      const hMonthIndex = (month + 1) % 12;
      const hDay = Math.min(29, Math.max(1, (day + 11) % 30));
      return `${hDay} ${hijriMonths[hMonthIndex]} ${hYear} H`;
    }
  } catch {
    // fallback
  }
  return '9 Rabi\'ul Akhir 1448 H';
}

